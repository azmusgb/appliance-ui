#!/usr/bin/env python3
"""fonts/archivo-latin-ui.woff2 -> dist/display/fonts/*.vlw (LovyanGFX / TFT_eSPI smooth fonts) and dist/display/fonts.h.

Display-kit K3: Archivo at the display's sizes (fs3 14, fs4 16, fs5 20, fs6 26) and a readout face at fs7 34 at 75% width.
Latin only. Run with `npm run fonts` after changing the sizes or the face; the .vlw files are committed, so building or
testing the kit needs neither Python nor Pillow (a dev-only dependency of this one script: Pillow reads the variable woff2
and rasterizes it with FreeType, where Node has no rasterizer).

VLW layout (Processing, as TFT_eSPI and LovyanGFX read it), all int32 big-endian:
  header: glyph count, version 11, line height, 0, ascent, descent
  per glyph: unicode, height, width, x advance, dY (top above the baseline), dX (left of the origin), 0
  then each glyph's bitmap in the same order: height x width bytes of 8-bit coverage.
"""
import struct
import sys
from pathlib import Path

from PIL import Image, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'fonts' / 'archivo-latin-ui.woff2'
OUT = ROOT / 'dist' / 'display' / 'fonts'

# name, px, weight, width (%). Body at 500 (the kit's chip and unit weight, steady on a small panel); readout at the
# kit's 650 and 75% width, as .ui-readout.
FACES = [
    ('archivo-14', 14, 500, 100),
    ('archivo-16', 16, 500, 100),
    ('archivo-20', 20, 500, 100),
    ('archivo-26', 26, 500, 100),
    ('archivo-readout-34', 34, 650, 75),
]
# Latin only: ASCII, Latin-1, and the punctuation the kit writes with (dashes, curly quotes, bullet, ellipsis, minus).
CODES = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))
         + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2212])


def raw(mask):
    return Image.Image()._new(mask).tobytes()


def build(name, px, weight, width):
    font = ImageFont.truetype(str(SRC), px, layout_engine=ImageFont.Layout.BASIC)
    font.set_variation_by_axes([weight, width])
    ascent, descent = font.getmetrics()
    notdef_ch = chr(0xE000)  # private use: the font has no glyph, so this draws its .notdef
    notdef = raw(font.getmask(notdef_ch, 'L')), font.getlength(notdef_ch)
    glyphs, missing = [], []
    for code in CODES:
        ch = chr(code)
        mask, (ox, oy) = font.getmask2(ch, 'L', anchor='ls')
        w, h = mask.size
        data = raw(mask)
        adv = round(font.getlength(ch))
        if code != 0x20 and code != 0xA0 and (data, font.getlength(ch)) == notdef:
            missing.append(ch)
            continue
        if code in (0x20, 0xA0):
            w = h = 0
            data = b''
        glyphs.append((code, h, w, adv, -oy, ox, data))
    body = struct.pack('>6i', len(glyphs), 11, ascent + descent, 0, ascent, descent)
    for code, h, w, adv, dy, dx, _ in glyphs:
        body += struct.pack('>7i', code, h, w, adv, dy, dx, 0)
    body += b''.join(g[6] for g in glyphs)
    (OUT / f'{name}.vlw').write_bytes(body)
    cap = -font.getbbox('H', anchor='ls')[1]
    digit = -font.getbbox('0', anchor='ls')[1]
    return dict(name=name, px=px, bytes=len(body), glyphs=len(glyphs), ascent=ascent, descent=descent, cap=cap, digit=digit, missing=missing)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = [build(*f) for f in FACES]
    for r in rows:
        print(f"{r['name']}.vlw {r['bytes']} bytes, {r['glyphs']} glyphs, ascent {r['ascent']} descent {r['descent']} cap {r['cap']}"
              + (f", missing {r['missing']}" if r['missing'] else ''))
    print('total', sum(r['bytes'] for r in rows), 'bytes')
    h = ['// generated by scripts/build-fonts.py from fonts/archivo-latin-ui.woff2: do not edit; change appliance-ui and sync',
         '#pragma once',
         '// Per kit font: the .vlw file, and the metrics the parts lay text out with (px). ascent and descent are the',
         '// line box above and below the baseline; cap is the height of a capital H, digit of a 0.',
         '#define UI_FONT_COUNT %d' % len(rows)]
    for i, r in enumerate(rows):
        n = r['name'].upper().replace('-', '_')
        h += [f'#define UI_{n}_FILE "{r["name"]}.vlw"', f'#define UI_{n}_BYTES {r["bytes"]}',
              f'#define UI_{n}_ASCENT {r["ascent"]}', f'#define UI_{n}_DESCENT {r["descent"]}',
              f'#define UI_{n}_CAP {r["cap"]}', f'#define UI_{n}_DIGIT {r["digit"]}']
    (ROOT / 'dist' / 'display' / 'fonts.h').write_text('\n'.join(h) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
