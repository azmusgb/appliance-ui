#!/usr/bin/env node
// tokens.json, tools.json, pages.json and src/ → dist/ (including the display kit's headers, dist/display/). Fails when a text/background pair is below WCAG AA in either mode, or when
// the tool registry has a problem (a duplicate id, a host off the real name outside the D4 boundary, …), or when the
// page list has one (a page with no way in, two pages on one address, a tool that isn't in the registry, …).
// Usage: node scripts/build.mjs [--tokens <path>] [--tools <path>] [--pages <path>] [--out <dir>]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { contrast, flatten, mix, rgb565, isHex } from './lib/color.mjs';
import { check, toolsJs, toolsH } from './lib/tools.mjs';
import { checkPages, pagesJs, pagesJson } from './lib/pages.mjs';
import { failures as measured } from './lib/contrast-report.mjs';
import { loadWords, checkWords, wordsH, needsH } from './lib/words.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, fallback) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : fallback; };
const tokensPath = arg('--tokens', path.join(root, 'tokens.json'));
const toolsPath = arg('--tools', path.join(root, 'tools.json'));
const pagesPath = arg('--pages', path.join(root, 'pages.json'));
const out = arg('--out', path.join(root, 'dist'));
const t = JSON.parse(fs.readFileSync(tokensPath, 'utf8'));
const kebab = s => s.replace(/([a-z])([A-Z0-9])/g, '$1-$2').toLowerCase();
const snake = s => kebab(s).replace(/-/g, '_').toUpperCase();

// Text colours on the three backgrounds they sit on (the page, a card, the well), and the accent's own label.
const BGS = ['bg', 'surface', 'surface2'];
const PAIRS = [...['text', 'muted', 'accentText', 'ok', 'warn', 'bad', 'unknown'].flatMap(fg => BGS.map(bg => [fg, bg])), ['onAccent', 'accent']];
const failures = [];
for (const mode of ['dark', 'light']) {
  for (const [fg, bg] of PAIRS) {
    const ratio = contrast(t.color[fg][mode], t.color[bg][mode]);
    if (ratio < 4.5) failures.push(`${mode} ${fg} on ${bg}: ${ratio.toFixed(2)} < 4.5`);
  }
  // Status text on a tint of itself: chips and the header badge (18%), the danger button (16%).
  for (const [kind, colours, p] of [['chip', ['ok', 'warn', 'bad', 'unknown'], 0.18], ['danger', ['bad'], 0.16]]) {
    for (const fg of colours) for (const bg of BGS) {
      const c = t.color[fg][mode], ratio = contrast(c, mix(c, t.color[bg][mode], p));
      if (ratio < 4.5) failures.push(`${mode} ${fg} ${kind} on ${bg}: ${ratio.toFixed(2)} < 4.5`);
    }
  }
  // A selected tab or chip in the accent: accent text on a 14% accent tint, and on accentSoft as the apps lay it.
  for (const bg of BGS) {
    const B = t.color[bg][mode];
    const tab = contrast(t.color.accentText[mode], mix(t.color.accent[mode], B, 0.14));
    if (tab < 4.5) failures.push(`${mode} accentText tab on ${bg}: ${tab.toFixed(2)} < 4.5`);
    const soft = contrast(t.color.accentText[mode], flatten(t.color.accentSoft[mode], B));
    if (soft < 4.5) failures.push(`${mode} accentText on accentSoft over ${bg}: ${soft.toFixed(2)} < 4.5`);
  }
  // A field's border is a UI boundary: 3:1 against what is around it.
  for (const bg of BGS) {
    const ratio = contrast(t.color.fieldLine[mode], t.color[bg][mode]);
    if (ratio < 3) failures.push(`${mode} fieldLine on ${bg}: ${ratio.toFixed(2)} < 3`);
  }
}
// The focus ring, field borders and lamp dots at 3:1 (WCAG 1.4.11), as docs/contrast.md lists them.
for (const f of measured(t)) if (!failures.includes(f)) failures.push(f);
if (failures.length) { console.error('Contrast below WCAG AA:\n' + failures.join('\n')); process.exit(1); }

const registry = JSON.parse(fs.readFileSync(toolsPath, 'utf8'));
const problems = check(registry);
if (problems.length) { console.error('tools.json:\n' + problems.join('\n')); process.exit(1); }
const pageList = JSON.parse(fs.readFileSync(pagesPath, 'utf8'));
const pageProblems = checkPages(pageList, registry);
if (pageProblems.length) { console.error('pages.json:\n' + pageProblems.join('\n')); process.exit(1); }

// A10 D1: sizes and space are rem (today's px at a 16 px root), and the root grows on one curve: 100% of the browser's
// size at fluid.from px wide to fluid.scale times it at fluid.to px, then stops. In % and rem, so a reader's own text
// size still scales everything. The display's tokens.h keeps the px (D5).
const rem = px => `${px / 16}rem`;
const { from, to, scale } = t.fluid;
const slope = 16 * (scale - 1) / (to - from);
const fix = n => +n.toFixed(4);
const rootSize = `html{font-size:clamp(100%, ${fix((16 - slope * from) / 16)}rem + ${fix(slope * 100)}vw, ${fix(scale * 100)}%)}`;
const banner = `generated by appliance-ui v${t.version} from tokens.json — do not edit; change appliance-ui and sync`;
// Colours and the two shadows differ by mode; everything in `fixed` is the same in both.
const vars = mode => Object.entries(t.color).map(([k, v]) => `--ui-${kebab(k)}:${v[mode]};`).join('')
  + Object.entries(t.shadow).map(([k, v]) => `--ui-shadow-${k.slice(1)}:${v[mode]};`).join('');
// 2.22 (Pi Hub A22 step 13): a person who asks their device for more contrast gets each colour named in
// tokens.json's contrastMore redrawn as a stronger colour the kit already has (muted text as text, each line as the
// next line up). No new colour, so no new pair to measure: every result is a row docs/contrast.md already has.
for (const [k, to] of Object.entries(t.contrastMore || {})) {
  if (!t.color[k] || !t.color[to]) { console.error(`tokens.json contrastMore: ${k} → ${to} names a colour that is not in color`); process.exit(1); }
}
const more = mode => Object.entries(t.contrastMore || {}).map(([k, to]) => `--ui-${kebab(k)}:${t.color[to][mode]};`).join('');
const fixed = [
  `--ui-font:${t.font.sans};`, `--ui-mono:${t.font.mono};`,
  ...Object.entries(t.font.stretch).map(([k, v]) => `--ui-stretch-${k}:${v}%;`),
  ...Object.entries(t.size).map(([k, v]) => `--ui-fs-${k.slice(2)}:${rem(v)};`),
  ...Object.entries(t.radius).map(([k, v]) => `--ui-r-${k.slice(1)}:${v}px;`),
  `--ui-space:${rem(t.space.unit)};`, `--ui-header-h:${rem(t.headerHeight)};`,
  '--ui-header-total:calc(var(--ui-header-h) + env(safe-area-inset-top, 0px));',
  // 2.19 (Pi Hub A22 1.3): the steps of space, the pill, the backdrop, motion and the layers. Web only: tokens.h
  // keeps its px sizes and colours, because the display draws no sheet, shadow or animation from the kit.
  ...Object.entries(t.space.steps).map(([k, v]) => `--ui-s-${k.slice(1)}:${rem(v)};`),
  `--ui-r-pill:${t.pill}px;`, `--ui-backdrop:${t.backdrop};`,
  `--ui-dur-1:${t.motion.dur1}ms;`, `--ui-dur-2:${t.motion.dur2}ms;`, `--ui-ease:${t.motion.ease};`,
  ...Object.entries(t.layer).map(([k, v]) => `--ui-z-${k}:${v};`),
].join('');
const css = `/* ${banner} */\n`
  // Archivo, cut to the weights (400–750) and widths (75–100%) the kit uses: body at 100%, headings and readouts narrower.
  + '@font-face{font-family:Archivo;src:url(archivo-latin-ui.woff2) format("woff2");font-weight:400 750;font-stretch:75% 100%;font-display:swap}\n'
  + `:root{${fixed}${vars('dark')}color-scheme:dark;}\n`
  + `@media (prefers-color-scheme: light){:root:not([data-theme="dark"]){${vars('light')}color-scheme:light;}}\n`
  + `[data-theme="light"]{${vars('light')}color-scheme:light;}\n`
  + `[data-theme="dark"]{${vars('dark')}color-scheme:dark;}\n`
  + (more('dark') ? `@media (prefers-contrast: more){:root{${more('dark')}}}\n`
    + `@media (prefers-contrast: more) and (prefers-color-scheme: light){:root:not([data-theme="dark"]){${more('light')}}}\n`
    + `@media (prefers-contrast: more){[data-theme="light"]{${more('light')}}[data-theme="dark"]{${more('dark')}}}\n` : '')
  + `${rootSize}\n`;

const h = [`// ${banner}`, '#pragma once', '// RGB565 of the dark values: the Workshop display is dark only.',
  ...Object.entries(t.color).filter(([, v]) => isHex(v.dark)).map(([k, v]) => `#define UI_COLOR_${snake(k)} ${rgb565(v.dark)}`),
  ...Object.entries(t.size).map(([k, v]) => `#define UI_FS_${k.slice(2)} ${v}`),
  ...Object.entries(t.radius).map(([k, v]) => `#define UI_R_${k.slice(1)} ${v}`), ''].join('\n');

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'tokens.css'), css);
fs.writeFileSync(path.join(out, 'tokens.h'), h);
fs.writeFileSync(path.join(out, 'tokens.json'), JSON.stringify(t, null, 2) + '\n');
const toolsBanner = `generated by appliance-ui v${t.version} from tools.json — do not edit; change appliance-ui and sync`;
fs.writeFileSync(path.join(out, 'tools.js'), toolsJs(registry, toolsBanner));
fs.writeFileSync(path.join(out, 'tools.h'), toolsH(registry, toolsBanner));
// The page list (A22 section 3): pages.json for a server or a test to read, pages.js for the pages themselves.
fs.writeFileSync(path.join(out, 'pages.json'), pagesJson(pageList));
fs.writeFileSync(path.join(out, 'pages.js'), pagesJs(pageList, `generated by appliance-ui v${t.version} from pages.json — do not edit; change appliance-ui and sync`));
// 2.0.0 retired the shared header (platform D3): an old build's copy must not linger in dist, or sync would ship it.
for (const f of ['appliance-header.js', 'appliance-header.lite.js']) fs.rmSync(path.join(out, f), { force: true });
fs.writeFileSync(path.join(out, 'components.css'), `/* ${banner} */\n` + fs.readFileSync(path.join(root, 'src/components.css'), 'utf8'));
fs.writeFileSync(path.join(out, 'needs.css'), `/* ${banner} */\n` + fs.readFileSync(path.join(root, 'src/needs.css'), 'utf8'));
// needs.js and the display's words.h/needs.h come from one table (src/words.json) and one PHRASES (src/needs.js).
const words = loadWords(root);
const wordProblems = checkWords(words);
if (wordProblems.length) { console.error('src/words.json:\n' + wordProblems.join('\n')); process.exit(1); }
const needsSrc = fs.readFileSync(path.join(root, 'src/needs.js'), 'utf8');
const needsBuilt = needsSrc.replace('const WORDS = null;', () => `const WORDS = ${JSON.stringify(words)};`);
if (needsBuilt === needsSrc) { console.error('src/needs.js: the `const WORDS = null;` line the build fills is gone'); process.exit(1); }
const needsMod = { exports: {} };
new Function('module', needsBuilt)(needsMod);
fs.writeFileSync(path.join(out, 'needs.js'), `// ${banner}\n` + needsBuilt);
fs.writeFileSync(path.join(out, 'needs.h'), needsH(needsMod.exports.PHRASES, banner));
fs.writeFileSync(path.join(out, 'words.h'), wordsH(words, banner));
fs.writeFileSync(path.join(out, 'palette.css'), `/* ${banner} */\n` + fs.readFileSync(path.join(root, 'src/palette.css'), 'utf8'));
fs.writeFileSync(path.join(out, 'palette.js'), `// ${banner}\n` + fs.readFileSync(path.join(root, 'src/palette.js'), 'utf8'));
fs.writeFileSync(path.join(out, 'motion.js'), `// ${banner}\n` + fs.readFileSync(path.join(root, 'src/motion.js'), 'utf8'));
fs.writeFileSync(path.join(out, 'confirm.js'), `// ${banner}\n` + fs.readFileSync(path.join(root, 'src/confirm.js'), 'utf8'));
fs.writeFileSync(path.join(out, 'shell.css'), `/* ${banner} */\n` + fs.readFileSync(path.join(root, 'src/shell.css'), 'utf8'));
fs.writeFileSync(path.join(out, 'shell.js'), `// ${banner}\n` + fs.readFileSync(path.join(root, 'src/shell.js'), 'utf8'));
fs.writeFileSync(path.join(out, 'backbar.js'), `// ${banner}\n` + fs.readFileSync(path.join(root, 'src/backbar.js'), 'utf8'));
// The display kit (K5): the C++ parts in src/display/ go to dist/display/ with the banner. Its fonts and fonts.h are
// generated by scripts/build-fonts.py (npm run fonts) and committed there, so they are not rebuilt here.
const displayOut = path.join(out, 'display');
fs.mkdirSync(displayOut, { recursive: true });
for (const f of fs.readdirSync(path.join(root, 'src/display'))) {
  const body = fs.readFileSync(path.join(root, 'src/display', f), 'utf8');
  fs.writeFileSync(path.join(displayOut, f), f.endsWith('.md') ? `<!-- ${banner} -->\n${body}` : `// ${banner}\n${body}`);
}
console.log(`built ${path.relative(process.cwd(), out) || out}: tokens.css, tokens.h, tokens.json, components.css, needs.js, needs.h, words.h, needs.css, palette.js, palette.css, shell.js, shell.css, motion.js, confirm.js, backbar.js, tools.js, tools.h, pages.json, pages.js, display/ (v${t.version})`);
