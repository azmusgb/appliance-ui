// K4 of the display-kit spec: the state words, the age rules and the Needs-you phrases are one table for the web and the
// display. dist/words.h and dist/needs.h are snapshot-tested; the web side (needs.js) reads the same table.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkWords, loadWords } from '../scripts/lib/words.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const body = f => read(f).slice(read(f).indexOf('\n') + 1);  // without the version banner
const mod = { exports: {} };
new Function('module', read('dist/needs.js'))(mod);
const { PHRASES, WORDS, ago } = mod.exports;

test('dist/words.h is the snapshot: state words and the age rules', () => {
  assert.equal(body('dist/words.h'), read('tests/fixtures/words-2.11.0.h'));
});

test('dist/needs.h is the snapshot: every phrase key and text from needs.js', () => {
  assert.equal(body('dist/needs.h'), read('tests/fixtures/needs-2.11.0.h'));
  const h = read('dist/needs.h');
  for (const [k, text] of Object.entries(PHRASES)) {
    assert.ok(h.includes(`#define UI_NEED_${k.toUpperCase()} ${JSON.stringify(text)}`), k);
    assert.ok(h.includes(`{ ${JSON.stringify(k)}, ${JSON.stringify(text)} },`), k);
  }
  assert.ok(h.includes(`#define UI_NEED_PHRASE_COUNT ${Object.keys(PHRASES).length}`));
});

test('the headers carry the version banner and the same table as src/words.json', () => {
  const w = loadWords(root);
  assert.deepEqual(WORDS, w);
  assert.match(read('dist/words.h'), /^\/\/ generated by appliance-ui v\d+\.\d+\.\d+ from tokens\.json/);
  assert.match(read('dist/needs.h'), /^\/\/ generated by appliance-ui v\d+\.\d+\.\d+ from tokens\.json/);
  for (const [k, v] of Object.entries(w.state)) assert.ok(read('dist/words.h').includes(`#define UI_WORD_${k.toUpperCase()} "${v}"`));
});

test('the state words are Up, Down, Unknown, Running and Waiting', () => {
  assert.deepEqual(WORDS.state, { up: 'Up', down: 'Down', unknown: 'Unknown', running: 'Running', waiting: 'Waiting' });
});

test('the display controls have their words (2.11.0): Back, Home, On, Off, Previous, Next, the Picker\'s two lines', () => {
  assert.deepEqual(WORDS.control, { back: 'Back', home: 'Home', on: 'On', off: 'Off', previous: 'Previous', next: 'Next',
    current_unknown: 'Current setting unknown', not_saved: 'Not saved', no_choices: 'Nothing to choose' });
  for (const [k, v] of Object.entries(WORDS.control)) assert.ok(read('dist/words.h').includes(`#define UI_TEXT_${k.toUpperCase()} "${v}"`), k);
});

test('the age rules word "now", "4 min ago" and "since …"', () => {
  assert.equal(ago(0), 'now');
  assert.equal(ago(59.9), 'now');
  assert.equal(ago(60), '1 min ago');
  assert.equal(ago(4 * 60 + 30), '4 min ago');
  assert.equal(ago(3599), '59 min ago');
  assert.equal(ago(3600), null);  // past the rules: "since 10:32"
  assert.equal(ago(-5), 'now');   // the other clock is ahead
  assert.equal(ago(NaN), null);
  assert.equal(ago('4'), null);
});

test('the build refuses a words table with a bad rule', () => {
  const w = loadWords(root);
  const bad = [
    [x => { x.state.up = 'Up %s'; }, /state\.up/],
    [x => { x.age.ago.reverse(); }, /in order of under/],
    [x => { x.age.ago[1].per = undefined; }, /\{n\} and per go together/],
    [x => { x.age.since = 'since'; }, /needs \{when\}/],
    [x => { x.state.up = 'Üp'; }, /plain ASCII/],
  ];
  for (const [change, re] of bad) {
    const x = structuredClone(w);
    change(x);
    assert.match(checkWords(x).join('\n'), re);
  }
  assert.deepEqual(checkWords(w), []);
});

