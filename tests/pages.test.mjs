// Pi Hub amendment A22, section 3 (step 12, K2): pages.json is the one list of the site's pages. dist/pages.json and
// dist/pages.js are built from it, a bad list fails the build and writes nothing, and the list holds 3.3's rows.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { checkPages } from '../scripts/lib/pages.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const node = args => spawnSync(process.execPath, args, { encoding: 'utf8' });
const list = JSON.parse(fs.readFileSync(path.join(root, 'pages.json'), 'utf8'));
const registry = JSON.parse(fs.readFileSync(path.join(root, 'tools.json'), 'utf8'));
const tmp = prefix => fs.mkdtempSync(path.join(os.tmpdir(), prefix));
const buildTo = (args = []) => { const out = tmp('ui-pages-'); return { out, r: node([path.join(root, 'scripts/build.mjs'), '--out', out, ...args]) }; };
const row = (l, id) => l.pages.find(p => p.id === id);
const problems = (edit, reg = registry) => { const l = structuredClone(list), r = structuredClone(reg); edit(l, r); return checkPages(l, r); };
const hub = list.pages.filter(p => p.system === 'hub');
const paths = ids => ids.map(id => row(list, id).path);

test('the list as it stands has no problem', () => {
  assert.deepEqual(checkPages(list, registry), []);
});

test('dist/pages.json and dist/pages.js hold exactly what pages.json says', async () => {
  const { out, r } = buildTo();
  assert.equal(r.status, 0, r.stderr);
  const json = JSON.parse(fs.readFileSync(path.join(out, 'pages.json'), 'utf8'));
  assert.deepEqual(json, { version: 1, areas: list.areas, pages: list.pages, redirects: list.redirects }, 'everything but the comment');
  const js = fs.readFileSync(path.join(out, 'pages.js'), 'utf8');
  assert.match(js, /^\/\/ generated by appliance-ui v\d+\.\d+\.\d+ from pages\.json/);
  const mod = await import(pathToFileURL(path.join(out, 'pages.js')).href);
  assert.deepEqual(mod.PAGES.map(p => ({ ...p, ...(p.reach && { reach: [...p.reach] }), ...(p.aliases && { aliases: [...p.aliases] }), ...(p.tools && { tools: [...p.tools] }) })), list.pages);
  assert.deepEqual(mod.AREAS.map(a => ({ ...a })), list.areas);
  assert.deepEqual(mod.REDIRECTS.map(r => ({ ...r })), list.redirects);
  assert.deepEqual({ ...mod.redirect('tools-files') }, { id: 'tools-files', to: 'developer-tools', card: 'files' });
  assert.equal(mod.redirect('printer'), null);
  assert.ok(Object.isFrozen(mod.page('developer-tools').cards) && mod.page('developer-tools').cards.every(c => Object.isFrozen(c)));
  assert.ok(Object.isFrozen(mod.PAGES) && mod.PAGES.every(p => Object.isFrozen(p) && Object.isFrozen(p.reach)));
  assert.equal(mod.page('printer').label, 'Printer');
  assert.equal(mod.page('nope'), null);
});

