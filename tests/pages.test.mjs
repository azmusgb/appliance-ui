// Pi Hub amendment A27 (D1 to D3): the Assistant's admin pages are cards in System, the five tools are cards of Developer tools,
// and the stages of Changes are a filter. A retired id keeps resolving through `redirects`.
const pagePaths = new Set(list.pages.filter(p => p.path).flatMap(p => [p.path, ...(p.aliases || [])]));
const cardPath = new Map(list.pages.flatMap(p => (p.cards || []).map(c => [c.path, c])));
const resolve = id => {
  const r = (list.redirects || []).find(x => x.id === id);
  if (!r) return row(list, id) || null;
  const to = row(list, r.to);
  return { ...to, ...(r.stage && { stage: r.stage }), ...(r.card && { card: to.cards.find(c => c.id === r.card) }) };
};

test('A27 D1: the five tools are cards of one Developer tools page, and their old ids redirect to them', () => {
  const dt = row(list, 'developer-tools');
  assert.deepEqual(dt.cards.map(c => [c.id, c.label, c.path, c.view]), [
    ['files', 'Files', '/assistant/tools/files', 'workbench'], ['repository', 'Repository', '/assistant/tools/repository', 'repoTools'],
    ['powershell', 'PowerShell', '/assistant/tools/powershell', 'powershell'], ['browser', 'Browser & computer', '/assistant/tools/browser', 'actions'],
    ['n8n', 'n8n workflows', '/assistant/tools/n8n', 'automations']]);
  assert.deepEqual([dt.role, dt.parent, dt.path, dt.tools], ['detail', 'assistant-system', '/assistant/tools', ['n8n']]);
  for (const id of ['tools-files', 'tools-repository', 'tools-powershell', 'tools-browser', 'tools-n8n']) {
    assert.equal(row(list, id), undefined, `${id} is no page`);
    const r = resolve(id);
    assert.equal(r.id, 'developer-tools', id);
    assert.equal(`tools-${r.card.id}`, id);
    assert.ok(cardPath.has(r.card.path), `${id}: its old address is the card's`);
  }
});

