test('a page with no way in, a wrong role or a missing parent is a problem', () => {
  const cases = [
    [l => { row(l, 'backups').reach = ['strip', 'map']; }, /backups\): every page has palette in reach/],
    [l => { row(l, 'backups').reach = ['strip', 'palette']; }, /backups\): every page has map in reach/],
    [l => { row(l, 'backups').reach = ['palette', 'map']; }, /a page must have strip in reach/],
    [l => { row(l, 'backups').reach.push('rail'); }, /only an area's landing page is in the rail/],
    [l => { row(l, 'lab-experiments').reach = ['palette', 'map']; }, /a tab must have tabs in reach/],
    [l => { delete row(l, 'lab-experiments').parent; }, /a tab needs a parent/],
    [l => { row(l, 'lab-experiments').parent = 'nope'; }, /names no other page/],
    [l => { row(l, 'lab-experiments').parent = 'lab-designs'; }, /the parent of a tab is a page/],
    [l => { row(l, 'changes-shipped').reach = ['palette', 'map']; }, /a filter must have chips in reach/],
    [l => { row(l, 'chat').reach = ['palette', 'map']; }, /a mode must have button in reach/],
    [l => { row(l, 'tools-files').reach = ['palette', 'map']; }, /a detail must name the page whose card opens it/],
    [l => { row(l, 'tools-files').reach[0] = 'card:nope'; }, /card:nope names no page/],
    [l => { row(l, 'wall').reach = ['palette', 'map']; }, /an ambient must have foot in reach/],
    [l => { row(l, 'privacy').reach = ['palette']; }, /privacy\): every page has map in reach/],
    [l => { row(l, 'backups').reach.push('sidebar'); }, /unknown way in "sidebar"/],
    [l => { row(l, 'backups').role = 'screen'; }, /role must be one of/],
    [l => { row(l, 'backups').parent = 'health'; }, /a page has no parent/],
    [l => { row(l, 'home').reach = ['palette', 'map']; }, /landing \(home\) must have rail in reach/],
  ];
  for (const [edit, why] of cases) assert.match(problems(edit).join('\n'), why);
});

test('two rows on one address are a problem, except a page and its first tab; an alias has one owner', () => {
  assert.match(problems(l => { row(l, 'versions').path = '/backups'; }).join('\n'), /path \/backups is already backups's/);
  assert.match(problems(l => { row(l, 'lab-designs').path = '/lab'; }).join('\n'), /only a page and its first tab share one/);
  assert.match(problems(l => { row(l, 'backups').aliases = ['/pi']; }).join('\n'), /alias \/pi is already health's/);
  assert.match(problems(l => { row(l, 'backups').aliases = ['/versions']; }).join('\n'), /alias \/versions \(backups\) is also versions's address/);
  assert.match(problems(l => { row(l, 'backups').aliases = ['https://x/']; }).join('\n'), /must be a plain path/);
  assert.match(problems(l => { row(l, 'backups').path = 'backups'; }).join('\n'), /path must be a Pi Hub address/);
  assert.match(problems(l => { row(l, 'models').path = '/models'; }).join('\n'), /path must be under \/assistant/);
});

test('an area is a rail entry with a landing page, and its strip has a cap', () => {
  const extra = id => ({ id, system: 'hub', area: 'household', label: id, purpose: 'x', path: `/${id}`, role: 'page', reach: ['strip', 'palette', 'map'] });
  assert.match(problems(l => { l.pages.push(extra('seventh')); }).join('\n'), /household\): its strip has 7 pages, more than 6/);
  assert.match(problems(l => { l.areas[2].landing = 'printer'; }).join('\n'), /landing must be a hub page of this area/);
  assert.match(problems(l => { l.areas[2].order = 9; }).join('\n'), /order must be 3/);
  assert.match(problems(l => { row(l, 'backups').area = 'media'; }).join('\n'), /area must be one of home, workshop, household, network, system/);
  assert.match(problems(l => { l.areas.push({ id: 'assistant', label: 'Assistant', order: 6, landing: 'ask' }); }).join('\n'), /assistant is not a rail area/);
});

test('a page\'s tools are in tools.json and offered to people, and every such tool is on a page', () => {
  assert.match(problems(l => { row(l, 'backups').tools = ['restic']; }).join('\n'), /"restic", which is not in tools\.json/);
  assert.match(problems(l => { row(l, 'internet').tools.push('status'); }).join('\n'), /status is retired/);
  assert.match(problems(l => { row(l, 'home').tools = ['hub']; }).join('\n'), /hub is retired, a machine address or the site itself/);
  assert.match(problems(l => { delete row(l, 'backups').tools; }).join('\n'), /tools\.json: backups is on no page's "Open in" row/);
  assert.match(problems((l, r) => { r.tools.push({ id: 'frigate', name: 'Frigate', host: 'frigate.rahe-home.duckdns.org', area: 'system', purpose: 'Cameras' }); }).join('\n'), /frigate is on no page/);
});

test('an Assistant page names its section and view, a Mac page needs the Mac, and stray or wrong fields are problems', () => {
  const cases = [
    [l => { row(l, 'chat').section = 'system'; }, /section must be one of ask, work, projects, improve/],
    [l => { row(l, 'models').section = 'work'; }, /an Assistant page in System has no section/],
    [l => { delete row(l, 'models').view; }, /view must be the Assistant's own view id/],
    [l => { delete row(l, 'models').needs; }, /needs the PC/],
    [l => { row(l, 'camera-fit').needs = 'pc'; }, /needs the Mac/],
    [l => { row(l, 'backups').needs = 'pc'; }, /a hub page has no needs/],
    [l => { row(l, 'backups').keywords = ['restore']; }, /unknown field keywords/],
    [l => { row(l, 'backups').built = true; }, /built can only be false/],
    [l => { delete row(l, 'backups').purpose; }, /a page needs its one-line purpose/],
    [l => { row(l, 'backups').purpose = 'What is backed up.'; }, /without a full stop/],
    [l => { row(l, 'backups').label = 'Sauvegardé'; }, /label must be printable ASCII/],
    [l => { row(l, 'backups').id = 'Backups'; }, /id must match/],
    [l => { l.pages.push({ ...row(l, 'backups'), path: '/b2' }); }, /duplicate id backups/],
    [l => { l.version = 2; }, /version: must be 1/],
    [l => { l.pages = []; }, /a non-empty list is required/],
  ];
  for (const [edit, why] of cases) assert.match(problems(edit).join('\n'), why);
});

