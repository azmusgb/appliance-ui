// Platform step 7, PR 7.1: the one tool registry (Decision 6). tools.json is the source; tools.js and tools.h are built
// from it, a bad registry fails the build, and an app's hand-edited copy fails its checker.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const node = args => spawnSync(process.execPath, args, { encoding: 'utf8' });
const registry = JSON.parse(fs.readFileSync(path.join(root, 'tools.json'), 'utf8'));
const tmp = prefix => fs.mkdtempSync(path.join(os.tmpdir(), prefix));
const buildTo = (args = []) => { const out = tmp('ui-tools-'); return { out, r: node([path.join(root, 'scripts/build.mjs'), '--out', out, ...args]) }; };
const withRegistry = edit => {
  const reg = structuredClone(registry);
  edit(reg);
  const file = path.join(tmp('ui-reg-'), 'tools.json');
  fs.writeFileSync(file, JSON.stringify(reg));
  return buildTo(['--tools', file]);
};

test('the generated tools.js holds exactly what tools.json says', async () => {
  const { out, r } = buildTo();
  assert.equal(r.status, 0, r.stderr);
  const js = fs.readFileSync(path.join(out, 'tools.js'), 'utf8');
  assert.ok(js.startsWith('// generated by appliance-ui v2.'), js.slice(0, 80));
  const mod = await import(pathToFileURL(path.join(out, 'tools.js')).href);
  assert.equal(mod.REAL, registry.real);
  assert.deepEqual(mod.TOOLS.map(t => ({ ...t })), registry.tools);
  assert.ok(Object.isFrozen(mod.TOOLS) && mod.TOOLS.every(Object.isFrozen));
});

test('toolUrl links a tool by its host, and an unknown id gives no link', async () => {
  const { out } = buildTo();
  const { toolUrl, tool, toolsFor } = await import(pathToFileURL(path.join(out, 'tools.js')).href);
  assert.equal(toolUrl('bambuddy'), 'https://bambuddy.rahe-home.duckdns.org/');
  assert.equal(toolUrl('assistant', '#run/42'), 'https://assistant.rahe-home.duckdns.org/#run/42');
  assert.equal(toolUrl('paperless', '//evil.com/x'), 'https://paperless.rahe-home.duckdns.org/evil.com/x');
  assert.equal(toolUrl('nope'), null);
  assert.equal(tool('nope'), null);
  assert.equal(tool('hub').name, 'Home');
  assert.deepEqual(toolsFor('documents').map(t => t.id), ['paperless', 'scan', 'homebox']);
  assert.deepEqual(toolsFor('workshop').map(t => t.id), ['bambuddy'], 'the D4 hosts are not offered to people');
});

test('the registry covers the gated tools of spec section 5.3 on their real names', () => {
  const byId = Object.fromEntries(registry.tools.map(t => [t.id, t]));
  for (const id of ['hub', 'assistant', 'bambuddy', 'paperless', 'scan', 'homebox', 'devices', 'adguard', 'network', 'status', 'backups', 'pi']) {
    assert.ok(byId[id], id);
    assert.equal(byId[id].host, `${id}.rahe-home.duckdns.org`, id);
    assert.equal(byId[id].boundary, undefined, id);
  }
  assert.ok(!byId.materials, 'Materials is retired: Bambuddy holds the spools');
});

test('the D4 entries are marked and are the only ones on home.arpa', () => {
  const d4 = registry.tools.filter(t => t.boundary === 'D4');
  assert.deepEqual(d4.map(t => [t.id, t.host]), [['display', 'home.home.arpa'], ['ota', 'updates.home.arpa']]);
  for (const t of registry.tools.filter(t => !t.boundary)) assert.doesNotMatch(t.host, /home\.arpa/, t.id);
});

test('tools.h has a host and name per tool, and the D4 marks', () => {
  const { out } = buildTo();
  const h = fs.readFileSync(path.join(out, 'tools.h'), 'utf8');
  assert.ok(h.startsWith('// generated by appliance-ui v2.'));
  assert.match(h, /#pragma once/);
  assert.match(h, /#define UI_TOOL_HUB_HOST "hub\.rahe-home\.duckdns\.org"/);
  assert.match(h, /#define UI_TOOL_ASSISTANT_NAME "Assistant"/);
  assert.match(h, /#define UI_TOOL_DISPLAY_HOST "home\.home\.arpa"/);
  assert.match(h, /#define UI_TOOL_OTA_BOUNDARY "D4"/);
  assert.doesNotMatch(h, /UI_TOOL_HUB_BOUNDARY/);
  assert.match(h, new RegExp(`#define UI_TOOL_COUNT ${registry.tools.length}\\b`));
});

test('a duplicate id fails the build and writes nothing', () => {
  const { out, r } = withRegistry(reg => reg.tools.push({ ...reg.tools[2] }));
  assert.equal(r.status, 1);
  assert.match(r.stderr, /duplicate id bambuddy/);
  assert.deepEqual(fs.readdirSync(out), []);
});

test('a host off the real name, an unknown area, a stray field or a non-ASCII name fails the build', () => {
  const cases = [
    [reg => { reg.tools[2].host = 'bambuddy.home.arpa'; }, /host must be bambuddy\.rahe-home\.duckdns\.org/],
    [reg => { reg.tools[2].host = 'https://10.0.0.30:8000/'; }, /host must be/],
    [reg => { reg.tools[2].area = 'materials'; }, /area must be one of/],
    [reg => { reg.tools[2].lan = 'http://x/'; }, /unknown field lan/],
    [reg => { reg.tools[2].name = 'Bam"buddyé'; }, /name must be printable ASCII/],
    [reg => { reg.tools.at(-1).boundary = 'D9'; }, /boundary can only be "D4"/],
    [reg => { reg.tools.at(-1).host = 'updates.rahe-home.duckdns.org'; }, /a D4 host stays on home\.arpa/],
    [reg => { reg.tools[2].id = 'Bam-buddy'; }, /id must match/],
    [reg => { reg.tools = []; }, /a non-empty list is required/],
  ];
  for (const [edit, why] of cases) {
    const { r } = withRegistry(edit);
    assert.equal(r.status, 1, String(why));
    assert.match(r.stderr, why);
  }
});

test('the shared header no longer ships, and a sync removes an app\'s old copy', () => {
  assert.equal(node([path.join(root, 'scripts/build.mjs')]).status, 0);
  for (const f of ['appliance-header.js', 'appliance-header.lite.js']) assert.ok(!fs.existsSync(path.join(root, 'dist', f)), f);
  const repo = tmp('ui-app-'), dir = path.join(repo, 'web/ui');
  fs.mkdirSync(dir, { recursive: true });
  for (const f of ['appliance-header.js', 'appliance-header.lite.js']) fs.writeFileSync(path.join(dir, f), '// 1.4.0 header');
  fs.writeFileSync(path.join(dir, 'VERSION'), JSON.stringify({ version: '1.4.0', files: { 'appliance-header.js': '0'.repeat(64), 'appliance-header.lite.js': '0'.repeat(64) } }));
  const r = node([path.join(root, 'scripts/sync.mjs'), repo, '--dir', 'web/ui']);
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /removed appliance-header\.js, appliance-header\.lite\.js/);
  assert.ok(!fs.existsSync(path.join(dir, 'appliance-header.js')));
  assert.ok(fs.existsSync(path.join(dir, 'tools.js')) && fs.existsSync(path.join(dir, 'tools.h')));
});

test('a hand edit to an app\'s tools.js fails both checkers, naming the file', () => {
  assert.equal(node([path.join(root, 'scripts/build.mjs')]).status, 0);
  const repo = tmp('ui-app-'), dir = path.join(repo, 'web/ui');
  assert.equal(node([path.join(root, 'scripts/sync.mjs'), repo, '--dir', 'web/ui']).status, 0);
  assert.equal(node([path.join(dir, 'verify.mjs'), dir]).status, 0);
  fs.appendFileSync(path.join(dir, 'tools.js'), 'TOOLS.push({ id: "x" });\n');
  const a = node([path.join(dir, 'verify.mjs'), dir]);
  const b = spawnSync('python3', ['-I', path.join(dir, 'verify.py'), dir], { encoding: 'utf8' });
  assert.equal(a.status, 1); assert.match(a.stderr, /tools\.js/);
  assert.equal(b.status, 1); assert.match(b.stderr, /tools\.js/);
});

test('Plex is a gated tool of Media, on its real name, and the only one in that area', async () => {
  const plex = registry.tools.find(t => t.id === 'plex');
  assert.ok(plex, 'plex is in the registry');
  assert.equal(plex.host, 'plex.rahe-home.duckdns.org');
  assert.equal(plex.name, 'Plex');
  assert.equal(plex.area, 'media');
  assert.equal(plex.boundary, undefined);
  const { out } = buildTo();
  const { toolsFor, toolUrl } = await import(pathToFileURL(path.join(out, 'tools.js')).href);
  assert.deepEqual(toolsFor('media').map(t => t.id), ['plex']);
  assert.equal(toolUrl('plex', '/web'), 'https://plex.rahe-home.duckdns.org/web');
  assert.match(fs.readFileSync(path.join(out, 'tools.h'), 'utf8'), /#define UI_TOOL_PLEX_HOST "plex\.rahe-home\.duckdns\.org"/);
});
