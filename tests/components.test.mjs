import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

test('components.css defines the shared classes using only --ui-* colours', () => {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-comp-'));
  const r = spawnSync(process.execPath, [path.join(root, 'scripts/build.mjs'), '--out', out], { encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr);
  const css = fs.readFileSync(path.join(out, 'components.css'), 'utf8');
  assert.ok(css.startsWith('/* generated by appliance-ui v'));
  for (const cls of ['ui-btn', 'ui-btn--primary', 'ui-btn--ghost', 'ui-btn--danger', 'ui-card', 'ui-chip', 'ui-chip--ok', 'ui-chip--warn',
    'ui-chip--bad', 'ui-chip--unknown', 'ui-chip--live', 'ui-field', 'ui-meter', 'ui-row', 'ui-empty', 'ui-title', 'ui-readout',
    'ui-readout--md', 'ui-readout--sm', 'ui-readout__unit', 'ui-notice', 'ui-notice--bad', 'ui-notice--warn', 'ui-skeleton',
    // 2.6.0 (Pi Hub amendment A7): one page anatomy, the lamp-right row, the inline confirm.
    'ui-page', 'ui-page__head', 'ui-page__title', 'ui-page__purpose', 'ui-page__tool', 'ui-strip', 'ui-chips', 'ui-faceplate', 'ui-faceplate--aside',
    'ui-faceplate__main', 'ui-faceplate__nameplate', 'ui-faceplate__caption', 'ui-faceplate__readings', 'ui-faceplate__actions', 'ui-faceplate__aside',
    'ui-section', 'ui-section__note', 'ui-rows', 'ui-row--lamp', 'ui-row__title', 'ui-row__detail', 'ui-row__value', 'ui-tools', 'ui-sources',
    'ui-confirm', 'ui-confirm__what',
    // 2.7.0 (DESIGN.md open differences 2 and 3): the table and the icon-only button.
    'ui-table', 'ui-table__num', 'ui-btn--icon']) {
    assert.match(css, new RegExp(`\\.${cls}[\\s{.,:>]`), cls);
  }
  assert.match(css, /:focus-visible\{[^}]*outline:2px solid var\(--ui-accent\)/);
  assert.match(css, /\.ui-field\{[^}]*box-sizing:border-box/, 'a full-width field stays inside its card');
  assert.match(css, /\.ui-field\{[^}]*border:1px solid var\(--ui-field-line\)/, 'field borders use the 3:1 token');
  assert.match(css, /\.ui-readout\{[^}]*font-stretch:var\(--ui-stretch-readout\);font-variant-numeric:tabular-nums/, 'readouts are narrow and tabular');
  assert.match(css, /\.ui-chip::before\{[^}]*background:currentColor/, 'a lamp is a dot in the status colour, beside its word');
  assert.match(css, /\.ui-card\{[^}]*border-radius:var\(--ui-r-2\)/, 'panels use the low radius');
  assert.match(css, /\.ui-btn\{[^}]*border-radius:var\(--ui-r-3\)/, 'controls are rounder than panels');
  assert.match(css, /@media \(prefers-reduced-motion:no-preference\)\{\.ui-skeleton\{animation:/, 'the wait pulse only runs when motion is welcome');
  // Motion lives only in no-preference blocks: the wait pulse and the attention beam (2.5.0).
  assert.doesNotMatch(css.replace(/@media \(prefers-reduced-motion:no-preference\)\{(?:[^{}]*\{[^}]*\})*\}/g, ''), /animation:/, 'no other animation');
  // 2.5.0: a card that needs a look gets a slow, faint beam along its edge; without motion it is a still tinted edge.
  assert.match(css, /\.ui-beam::after\{[^}]*pointer-events:none/, 'the beam never takes a click');
  assert.match(css, /@media \(prefers-reduced-motion:no-preference\)\{[^@]*\.ui-beam::after\{animation:ui-beam [6-9]s linear infinite\}/, 'the beam turns slowly, and only when motion is welcome');
  assert.match(css, /\.ui-beam--bad\{--ui-beam:var\(--ui-bad\)\}/);
  // 2.5.0: on a touch screen buttons and fields are 44 px, like the rest of the kit's targets (CSS review, 4 Nov).
  assert.match(css, /@media \(pointer:coarse\)\{\.ui-btn,\.ui-field\{min-height:44px\}\}/);
  // 2.6.0: the strip is underlined (one style in every app); the current page is marked by aria-current, not colour alone.
  assert.match(css, /\.ui-strip a\[aria-current="page"\],\.ui-strip a\[aria-current="true"\]\{[^}]*border-bottom-color:var\(--ui-accent\)/);
  assert.match(css, /\.ui-strip a\{[^}]*min-height:44px/, 'strip links are 44 px targets');
  assert.match(css, /@media \(pointer:coarse\)\{\.ui-chips :is\(a,button\)\{min-height:44px\}\}/, 'chips are 44 px on touch');
  assert.match(css, /\.ui-faceplate\{[^}]*border-radius:var\(--ui-r-2\)/, 'the faceplate is a panel: the low radius');
  assert.match(css, /\.ui-row--lamp>:first-child\{flex:1 1 220px\}/, 'the text takes the room, so lamps line up on the right');
  // 2.7.0: an icon-only button's outline is the 3:1 field line (the ghost border is decoration), and it is square.
  assert.match(css, /\.ui-btn--icon\{[^}]*border-color:var\(--ui-field-line\)/, 'icon-only buttons have a 3:1 boundary');
  assert.match(css, /\.ui-btn--icon\{[^}]*width:40px/);
  assert.match(css, /@media \(pointer:coarse\)\{\.ui-btn--icon\{width:44px\}\}/, 'and 44 px square on touch');
  // 2.7.0: a table for comparison: numbers right-aligned and tabular; on a phone each row stands alone with its labels.
  assert.match(css, /\.ui-table__num\{[^}]*text-align:right;font-variant-numeric:tabular-nums/);
  assert.match(css, /\.ui-table caption\{[^}]*text-align:left/);
  assert.match(css, /@media \(max-width:599px\)\{\.ui-table--stack[^}]*\{display:block\}/, 'a stacking table becomes rows on a phone');
  assert.match(css, /\.ui-table--stack td\[data-label\]::before\{content:attr\(data-label\)/, 'each cell keeps its column name');
  const code = css.replace(/\/\*[\s\S]*?\*\//g, '');
  assert.doesNotMatch(code, /#[0-9a-f]{3,8}\b/i, 'no literal hex colours');
  assert.doesNotMatch(code, /\brgba?\(/i, 'no literal rgb colours');
  const needs = fs.readFileSync(path.join(out, 'needs.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  assert.doesNotMatch(needs, /#[0-9a-f]{3,8}\b/i, 'needs.css: no literal hex colours');
  assert.doesNotMatch(needs, /\brgba?\(/i, 'needs.css: no literal rgb colours');
});

test('every --ui-* variable the CSS uses is a token the build defines (palette used --ui-surface2)', () => {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-vars-'));
  const r = spawnSync(process.execPath, [path.join(root, 'scripts/build.mjs'), '--out', out], { encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr);
  const tokens = fs.readFileSync(path.join(out, 'tokens.css'), 'utf8');
  const defined = new Set([...tokens.matchAll(/(--ui-[\w-]+):/g)].map((m) => m[1]));
  for (const f of ['components.css', 'needs.css', 'palette.css']) {
    const css = fs.readFileSync(path.join(out, f), 'utf8');
    for (const own of css.matchAll(/(--ui-[\w-]+):/g)) defined.add(own[1]);
    for (const [, name] of css.matchAll(/var\((--ui-[\w-]+)/g)) assert.ok(defined.has(name), `${f} uses undefined ${name}`);
  }
});
