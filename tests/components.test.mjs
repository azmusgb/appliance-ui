import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

test('components.css defines the shared classes using only --ui-* colours', () => {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-comp-'));
  const r = spawnSync(process.execPath, [path.join(root, 'scripts/build.mjs'), '--out', out], { encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr);
  const css = fs.readFileSync(path.join(out, 'components.css'), 'utf8');
  assert.ok(css.startsWith('/* generated by appliance-ui v'));
  for (const cls of ['ui-btn', 'ui-btn--primary', 'ui-btn--ghost', 'ui-btn--danger', 'ui-card', 'ui-chip', 'ui-chip--ok', 'ui-chip--warn',
    'ui-chip--bad', 'ui-chip--unknown', 'ui-chip--live', 'ui-field', 'ui-meter', 'ui-row', 'ui-empty', 'ui-title', 'ui-readout',
    'ui-readout--md', 'ui-readout--sm', 'ui-readout__unit', 'ui-notice', 'ui-notice--bad', 'ui-notice--warn', 'ui-skeleton']) {
    assert.match(css, new RegExp(`\\.${cls}[\\s{.,:>]`), cls);
  }
  assert.match(css, /:focus-visible\{[^}]*outline:2px solid var\(--ui-accent\)/);
  assert.match(css, /\.ui-field\{[^}]*box-sizing:border-box/, 'a full-width field stays inside its card');
  assert.match(css, /\.ui-field\{[^}]*border:1px solid var\(--ui-field-line\)/, 'field borders use the 3:1 token');
  assert.match(css, /\.ui-readout\{[^}]*font-stretch:var\(--ui-stretch-readout\);font-variant-numeric:tabular-nums/, 'readouts are narrow and tabular');
  assert.match(css, /\.ui-chip::before\{[^}]*background:currentColor/, 'a lamp is a dot in the status colour, beside its word');
  assert.match(css, /\.ui-card\{[^}]*border-radius:var\(--ui-r-2\)/, 'panels use the low radius');
  assert.match(css, /\.ui-btn\{[^}]*border-radius:var\(--ui-r-3\)/, 'controls are rounder than panels');
  assert.match(css, /@media \(prefers-reduced-motion:no-preference\)\{\.ui-skeleton\{animation:/, 'the wait pulse only runs when motion is welcome');
  assert.doesNotMatch(css.replace(/@media \(prefers-reduced-motion:no-preference\)\{[^}]*\}\}/, ''), /animation:/, 'no other animation');
  const code = css.replace(/\/\*[\s\S]*?\*\//g, '');
  assert.doesNotMatch(code, /#[0-9a-f]{3,8}\b/i, 'no literal hex colours');
  assert.doesNotMatch(code, /\brgba?\(/i, 'no literal rgb colours');
  const needs = fs.readFileSync(path.join(out, 'needs.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  assert.doesNotMatch(needs, /#[0-9a-f]{3,8}\b/i, 'needs.css: no literal hex colours');
  assert.doesNotMatch(needs, /\brgba?\(/i, 'needs.css: no literal rgb colours');
});
