import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const build = (args = []) => spawnSync(process.execPath, [path.join(root, 'scripts/build.mjs'), ...args], { encoding: 'utf8' });

test('rgb565 packs 5-6-5 bits of the colour', async () => {
  const { rgb565 } = await import('../scripts/lib/color.mjs');
  assert.equal(rgb565('#0a111c'), '0x0883');
  assert.equal(rgb565('#ffffff'), '0xFFFF');
});

test('contrast is the WCAG ratio', async () => {
  const { contrast } = await import('../scripts/lib/color.mjs');
  assert.ok(Math.abs(contrast('#ffffff', '#000000') - 21) < 0.01);
});

test('tokens.css has dark on :root, light by device and by data-theme, and the header height', () => {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-build-'));
  const r = build(['--out', out]);
  assert.equal(r.status, 0, r.stderr);
  const css = fs.readFileSync(path.join(out, 'tokens.css'), 'utf8');
  assert.ok(css.startsWith('/* generated by appliance-ui v'));
  const dark = css.slice(css.indexOf(':root{'), css.indexOf('}', css.indexOf(':root{')));
  assert.match(dark, /--ui-accent:#5ab4ff;/);
  assert.match(css, /@media \(prefers-color-scheme: light\)\{:root:not\(\[data-theme="dark"\]\)\{[^}]*--ui-accent:#1a6fc4;/);
  assert.match(css, /\[data-theme="light"\]\{[^}]*--ui-accent:#1a6fc4;/);
  assert.match(css, /--ui-header-h:48px;/);
  assert.match(css, /@media \(max-width:719px\)\{:root\{--ui-header-h:44px;\}\}/);
  assert.match(css, /--ui-surface-2:/);
  assert.match(css, /--ui-accent-text:/);
  assert.match(css, /@font-face\{font-family:Figtree;src:url\(figtree-latin-wght-normal\.woff2\) format\("woff2"\)/);
});

test('tokens.h has RGB565 colour constants', () => {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-build-'));
  assert.equal(build(['--out', out]).status, 0);
  const h = fs.readFileSync(path.join(out, 'tokens.h'), 'utf8');
  assert.ok(h.startsWith('// generated by appliance-ui v'));
  assert.match(h, /#define UI_COLOR_BG 0x[0-9A-F]{4}/);
  assert.match(h, /#define UI_COLOR_ACCENT 0x[0-9A-F]{4}/);
  assert.match(h, /#define UI_COLOR_ACCENT_TEXT 0x[0-9A-F]{4}/);
});

test('shipped tokens meet WCAG AA in both modes', async () => {
  const { contrast } = await import('../scripts/lib/color.mjs');
  const t = JSON.parse(fs.readFileSync(path.join(root, 'tokens.json'), 'utf8'));
  for (const mode of ['dark', 'light']) {
    const c = n => t.color[n][mode];
    for (const fg of ['text', 'muted', 'accentText', 'ok', 'warn', 'bad']) {
      for (const bg of ['bg', 'surface']) assert.ok(contrast(c(fg), c(bg)) >= 4.5, `${mode} ${fg} on ${bg}`);
    }
    assert.ok(contrast(c('onAccent'), c('accent')) >= 4.5, `${mode} onAccent on accent`);
  }
});

test('the build refuses tokens below AA and names the pair', () => {
  const t = JSON.parse(fs.readFileSync(path.join(root, 'tokens.json'), 'utf8'));
  t.color.muted.dark = '#555b62';
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-bad-'));
  fs.writeFileSync(path.join(dir, 'tokens.json'), JSON.stringify(t));
  const r = build(['--tokens', path.join(dir, 'tokens.json'), '--out', path.join(dir, 'dist')]);
  assert.notEqual(r.status, 0);
  assert.match(r.stderr, /dark muted on bg/);
});

// One home, step 5: chips, the danger button and the header badge are status text on a tint of itself; field borders
// are a UI boundary (3:1). The gate covers both, in both modes.
const withColors = (over) => {
  const t = JSON.parse(fs.readFileSync(path.join(root, 'tokens.json'), 'utf8'));
  for (const [k, v] of Object.entries(over)) t.color[k] = { ...t.color[k], ...v };
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-gate-'));
  fs.writeFileSync(path.join(dir, 'tokens.json'), JSON.stringify(t));
  return build(['--tokens', path.join(dir, 'tokens.json'), '--out', path.join(dir, 'dist')]);
};

test('the gate refuses 1.0 light status colours on their own tints, and faint field borders', () => {
  const r = withColors({ bad: { light: '#c9372c' }, fieldLine: { dark: '#5b6c82', light: '#c6d0dc' } });
  assert.notEqual(r.status, 0);
  assert.match(r.stderr, /light bad chip on bg: 3\.68 < 4\.5/);
  assert.match(r.stderr, /light bad danger on surface/);
  assert.match(r.stderr, /light fieldLine on bg: 1\.45 < 3/);
});

test('1.1 tokens pass the wider gate and ship --ui-field-line and --ui-header-total', () => {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-build-'));
  const r = build(['--out', out]);
  assert.equal(r.status, 0, r.stderr);
  const css = fs.readFileSync(path.join(out, 'tokens.css'), 'utf8');
  assert.match(css, /:root\{[^}]*--ui-field-line:#5b6c82;/);
  assert.match(css, /\[data-theme="light"\]\{[^}]*--ui-field-line:#7f8b9b;[^}]*/);
  assert.match(css, /\[data-theme="light"\]\{[^}]*--ui-bad:#b02a20;/);
  assert.match(css, /--ui-header-total:calc\(var\(--ui-header-h\) \+ env\(safe-area-inset-top, 0px\)\);/);
  const t = JSON.parse(fs.readFileSync(path.join(out, 'tokens.json'), 'utf8'));
  assert.equal(t.version, '1.1.0');
});
