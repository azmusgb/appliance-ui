test('the accent is told apart from the ok lamp: hue at least 40 degrees away in both modes', async () => {
  const t = JSON.parse(fs.readFileSync(path.join(root, 'tokens.json'), 'utf8'));
  const hue = hex => { const [r, g, b] = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255);
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn;
    const h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; return (h * 60 + 360) % 360; };
  for (const mode of ['dark', 'light']) {
    const gap = Math.abs(hue(t.color.accent[mode]) - hue(t.color.ok[mode]));
    assert.ok(Math.min(gap, 360 - gap) >= 40, `${mode}: ${gap.toFixed(0)}`);
  }
});

